func TestUnit_ItemgenDefinitionTestContract(t *testing.T) {
	t.Parallel()

	r := fabricitem.NewResourceFabricItemDefinition(fabricitem.ResourceFabricItemDefinition{
		DefinitionFormats: []fabricitem.DefinitionFormat{
			{Type: fabricitem.DefinitionFormatDefault, Paths: []string{"definition.json"}},
		},
	})
	var response resource.SchemaResponse
	r.Schema(t.Context(), resource.SchemaRequest{}, &response)
	require.False(t, response.Diagnostics.HasError())
	definition, ok := response.Schema.Attributes["definition"].(schema.MapNestedAttribute)
	require.True(t, ok)
	require.True(t, definition.NestedObject.Attributes["source"].IsRequired())

	templatePath := filepath.Join("..", "..", "..", "tools", "itemgen", "templates", "definition", "resource_item_test.go.tmpl")
	tmpl, err := template.ParseFiles(templatePath)
	require.NoError(t, err)

	var generated bytes.Buffer
	require.NoError(t, tmpl.Execute(&generated, map[string]any{
		"Package":        "probe",
		"TypeInfo":       "Probe",
		"DefinitionPath": "definition.json",
		"IsSPNSupported": false,
	}))
	require.NotContains(t, generated.String(), "must be a valid JSON string")
	require.NotContains(t, generated.String(), "must be a valid YAML string")

	file, err := parser.ParseFile(token.NewFileSet(), "resource_probe_test.go", generated.Bytes(), parser.AllErrors)
	require.NoError(t, err)

	var crud *ast.FuncDecl

	for _, declaration := range file.Decls {
		if function, ok := declaration.(*ast.FuncDecl); ok && function.Name.Name == "TestUnit_ProbeResource_CRUD" {
			crud = function
		}
	}

	require.NotNil(t, crud)

	definitions := 0

	ast.Inspect(crud, func(node ast.Node) bool {
		config, ok := node.(*ast.CompositeLit)
		if !ok {
			return true
		}

		value := itemgenMapValue(t, config, "definition")
		if value == nil {
			return true
		}

		definitions++
		format, ok := itemgenMapValue(t, config, "format").(*ast.BasicLit)
		require.True(t, ok, "definition configuration must include its format")
		require.Equal(t, `"Default"`, format.Value)

		parts, ok := value.(*ast.CompositeLit)
		require.True(t, ok, "definition must be a nested map, not a string")
		require.Len(t, parts.Elts, 1)
		part, ok := parts.Elts[0].(*ast.KeyValueExpr)
		require.True(t, ok)
		key, ok := part.Key.(*ast.BasicLit)
		require.True(t, ok)

		path, err := strconv.Unquote(key.Value)
		require.NoError(t, err)
		require.Equal(t, `"definition.json"`, path)

		attributes, ok := part.Value.(*ast.CompositeLit)
		require.True(t, ok)
		require.NotNil(t, itemgenMapValue(t, attributes, "source"))

		return true
	})
	require.Equal(t, 2, definitions, "create and update must exercise the definition map")
}

func itemgenMapValue(t *testing.T, literal *ast.CompositeLit, name string) ast.Expr {
	t.Helper()

	for _, element := range literal.Elts {
		entry, ok := element.(*ast.KeyValueExpr)
		if !ok {
			continue
		}

		key, ok := entry.Key.(*ast.BasicLit)
		if !ok || key.Kind != token.STRING {
			continue
		}

		value, err := strconv.Unquote(key.Value)
		require.NoError(t, err)

		if value == name {
			return entry.Value
		}
	}

	return nil
}
